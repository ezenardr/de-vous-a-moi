// Creates the least-privilege role the app uses at runtime (`devousamoi_app`): it can read and write
// rows in the public tables, and nothing else (no CREATE/ALTER/DROP, no superuser, no other schemas).
// `postgres` stays for migrations only (MIGRATION_DATABASE_URL).
//
// Run once, as postgres, with writes allowed:
//   DB_ALLOW_WRITES=true node --env-file=.env.local scripts/create-app-role.mjs
// It generates a random password, never prints it, and writes the app's new connection string to
// .env.app-role.local (git-ignored) for you to copy into Vercel as DATABASE_URL (mark it Sensitive).
// Re-running rotates the password.
import { randomBytes } from "node:crypto";
import { writeFileSync } from "node:fs";
import pg from "pg";
import { databaseSsl } from "../src/server/db/connection.ts";

const ROLE = "devousamoi_app";
if (process.env.DB_ALLOW_WRITES !== "true") throw new Error("Needs DB_ALLOW_WRITES=true (this changes the production database).");

const admin = new URL(process.env.MIGRATION_DATABASE_URL ?? process.env.DATABASE_URL);
if (decodeURIComponent(admin.username) === ROLE) throw new Error("Run this with the postgres connection string, not the app role's.");
const database = decodeURIComponent(admin.pathname.slice(1));
const password = randomBytes(32).toString("base64url");

const client = new pg.Client({ connectionString: admin.toString(), ssl: databaseSsl() });
await client.connect();
const ident = (s) => client.escapeIdentifier(s);
const literal = (s) => client.escapeLiteral(s);
try {
  await client.query("begin");
  const exists = (await client.query("select 1 from pg_roles where rolname = $1", [ROLE])).rowCount > 0;
  await client.query(
    `${exists ? "alter" : "create"} role ${ident(ROLE)} with login password ${literal(password)} nosuperuser nocreatedb nocreaterole noreplication nobypassrls`,
  );
  for (const sql of [
    `grant connect on database ${ident(database)} to ${ident(ROLE)}`,
    `grant usage on schema public to ${ident(ROLE)}`,
    `grant select, insert, update, delete on all tables in schema public to ${ident(ROLE)}`,
    `grant usage, select on all sequences in schema public to ${ident(ROLE)}`,
    // Tables and sequences created later by migrations (run as postgres) get the same rights.
    `alter default privileges for role postgres in schema public grant select, insert, update, delete on tables to ${ident(ROLE)}`,
    `alter default privileges for role postgres in schema public grant usage, select on sequences to ${ident(ROLE)}`,
  ]) {
    await client.query(sql);
  }
  await client.query("commit");
} catch (error) {
  await client.query("rollback");
  throw error;
} finally {
  await client.end();
}

const appUrl = new URL(admin.toString());
appUrl.username = ROLE;
appUrl.password = password;
writeFileSync(
  ".env.app-role.local",
  `# Generated by scripts/create-app-role.mjs. Copy into Vercel as DATABASE_URL (Sensitive), then delete this file.\nDATABASE_URL=${appUrl.toString()}\n`,
);
console.log(`Role ${ROLE} ${"ready"}. Its connection string is in .env.app-role.local (not printed).`);
