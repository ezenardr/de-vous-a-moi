// Generates src/components/icons/mingcute.tsx from the MingCute 2.x SVGs (the set used in Figma).
// Add a name below and run `node scripts/gen-icons.mjs`.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const ICONS = [
  "book-3-fill", "board-fill", "board-line", "video-fill", "video-line", "folder-3-fill", "folder-3-line",
  "bookmarks-fill", "bookmarks-line", "mail-open-fill", "user-4-fill", "arrow-right-up-line", "search-line",
  "calendar-month-fill", "time-fill", "teacup-fill", "building-6-fill", "mic-fill", "computer-fill",
  "right-line", "left-line", "menu-line", "close-line", "play-fill", "chart-bar-fill", "information-line",
  "exit-line", "user-star-line", "quill-pen-line", "more-1-line", "share-forward-fill", "heart-line",
  "heart-fill", "comment-fill", "eye-fill",
];

const root = "node_modules/mingcute_icon/svg";
const files = new Map();
for (const dir of readdirSync(root)) {
  for (const file of readdirSync(path.join(root, dir))) files.set(file.replace(/\.svg$/, ""), path.join(root, dir, file));
}

const pascal = (name) => name.split("-").map((p) => p[0].toUpperCase() + p.slice(1)).join("");
const out = [
  "// Generated by scripts/gen-icons.mjs from mingcute_icon@2.9.72. Do not edit.",
  'import type { SVGProps } from "react";',
  "",
  "type IconProps = SVGProps<SVGSVGElement> & { size?: number };",
  "",
  "function svg(d: string, rule: \"evenodd\" | \"nonzero\", displayName: string) {",
  "  const Icon = ({ size = 20, ...props }: IconProps) => (",
  '    <svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" width={size} height={size} fill="currentColor" aria-hidden {...props}>',
  "      <path fillRule={rule} clipRule={rule} d={d} />",
  "    </svg>",
  "  );",
  "  Icon.displayName = displayName;",
  "  return Icon;",
  "}",
  "",
];
for (const name of ICONS) {
  const file = files.get(name.replaceAll("-", "_"));
  if (!file) throw new Error(`MingCute icon not found: ${name}`);
  // Each icon has a transparent 24x24 guide path, then the drawn path(s) with fill="#09244B".
  const source = readFileSync(file, "utf8");
  const paths = [...source.matchAll(/<path fill="#09244B"[^>]*\sd="([^"]+)"/g)].map((m) => m[1]);
  if (paths.length === 0) throw new Error(`No drawable path in ${file}`);
  const rule = /fill-rule="evenodd"/.test(source) ? "evenodd" : "nonzero";
  out.push(`export const ${pascal(name)}Icon = svg(${JSON.stringify(paths.join(" "))}, "${rule}", "${pascal(name)}Icon");`);
}
writeFileSync("src/components/icons/mingcute.tsx", out.join("\n") + "\n");
console.log(`wrote ${ICONS.length} icons`);
